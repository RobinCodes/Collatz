def table_primcycles(limit: int) -> None:
    cycles, basins, failed, peak = primality_census(limit)
    lines = [f"Primality map  f(n) = 3n+1 (n prime), n/2 (n even), n+1 (else)",
             f"seeds 1..{limit}:  {failed} failed to become periodic",
             "=" * 74, ""]
    tex = []
    for k, (c, bn) in enumerate(zip(cycles, basins), start=1):
        lines.append(f"  C{k}: period {len(c)}, basin {100*bn/limit:.1f}%")
        lines.append(f"      {list(c)}")
        tex.append(r"  C_{%d} &= \{%s\}, &&\text{period } %d, &&%.1f\%%"
                   r" \text{ of seeds}%s" %
                   (k, ",".join(str(x) for x in c), len(c),
                    100.0 * bn / limit, r"," if k < len(cycles) else "."))
    write("primcycles.txt", "\n".join(lines) + "\n")
    write("primcycles.tex", "%% generated by generate_data.py -- do not edit\n"
          + " \\\\\n".join(tex) + "\n")
    FACTS["PrimSeeds"] = _num(limit)
    FACTS["PrimPeak"] = r"%.1f \times 10^{%d}" % (
        peak / 10 ** int(math.log10(peak)), int(math.log10(peak)))
    FACTS["PrimCycleCount"] = {1: "one", 2: "two", 3: "three"}.get(
        len(cycles), str(len(cycles)))


#: (floor, first seed, how many seeds).  Each row of the density table is its
#: OWN sample, drawn just above the floor it reports -- orbits started at
#: n <= 200000 never reach 10^8 at all, so a single seed range cannot fill the
#: table.  An earlier version printed the rows without saying this, and the
#: counts were visibly non-monotone as a result.
PRIME_BANDS = [(10 ** 3, 1, 4000),
               (10 ** 4, 10 ** 5, 2500),
               (10 ** 6, 10 ** 7, 1800),
               (10 ** 8, 10 ** 9, 1200),
               (10 ** 11, 10 ** 12, 900)]


def table_primedensity(quick: bool) -> None:
    """Density of primes among the odd values on the TRANSIENT part of an
    orbit of the primality map, above a floor.

    Cycles are excluded: they are short and prime-rich, and counting them
    makes the density look alarmingly close to the ln2/ln3 threshold.
    """
    pm = QA.primality_map()
    rows = []
    for floor, lo, count in PRIME_BANDS:
        if quick:
            count = min(count, 120)
        tot = pr = 0
        for seed in range(lo, lo + count):
            traj, ci = pm.orbit(seed, max_steps=6000, value_cap=10 ** 40)
            seg = traj[:ci] if ci is not None else traj
            for y in seg:
                if y % 2 == 1 and y > floor:
                    tot += 1
                    pr += QA.is_prime(y)
        rows.append((floor, lo, count, tot, pr,
                     100.0 * pr / max(tot, 1), 100.0 / math.log(floor)))

    lines = ["Primes among odd transient values of the primality map",
             "(each row is its own sample of seeds, drawn just above its "
             "floor)", "=" * 74, "",
             f"{'above':>10} {'seeds':>24} {'odd':>8} {'prime':>8} "
             f"{'density':>9} {'1/ln n':>9}"]
    for floor, lo, count, tot, pr, dens, ref in rows:
        lines.append(f"{floor:>10.0e} {f'{lo}..{lo+count-1}':>24} {tot:>8} "
                     f"{pr:>8} {dens:>8.1f}% {ref:>8.1f}%")
    write("primedensity.txt", "\n".join(lines) + "\n")

    def p10(x):
        return "10^{%d}" % round(math.log10(x))

    tex = [r"$%s$ & $%s$ & $%s$ & $%s$ & $%s$ & $%.1f\%%$ & $%.1f\%%$ \\" %
           (p10(floor), _num(lo), _num(count), _num(tot), _num(pr), dens, ref)
           for floor, lo, count, tot, pr, dens, ref in rows]
    write("primedensity.tex",
          "%% generated by generate_data.py -- do not edit\n"
          + "\n".join(tex) + "\n")
    # the same count taken over WHOLE orbits, cycles included -- the
    # measurement the paper warns against, quoted so the warning is concrete
    whole = []
    for lo, hi in ((1, 400), (10 ** 5, 10 ** 5 + 200)):
        tot = pr = 0
        for seed in range(lo, hi):
            traj, _ = pm.orbit(seed, max_steps=6000, value_cap=10 ** 40)
            for y in traj:
                if y % 2 == 1:
                    tot += 1
                    pr += QA.is_prime(y)
        whole.append(100.0 * pr / max(tot, 1))
    FACTS["PrimeDensWholeLo"] = "%d" % round(min(whole))
    FACTS["PrimeDensWholeHi"] = "%d" % round(max(whole))

    top = rows[-1]
    FACTS["PrimeDensTopFloor"] = "10^{%d}" % round(math.log10(top[0]))
    FACTS["PrimeDensTop"] = "%.1f" % top[5]
    FACTS["PrimeDensTopRef"] = "%.1f" % top[6]
    FACTS["PrimeDensRatio"] = "%.1f" % (top[5] / top[6])


