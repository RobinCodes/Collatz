#  Table 2 -- carykh's 6x6 grid, fully resolved
# ======================================================================

def table_carykh() -> None:
    lines = ["carykh's 6x6 grid (a = 0..5 down, b = 0..5 across), fully resolved",
             "=" * 78, ""]
    tex = []
    tally: Dict[str, int] = {}
    for a in range(6):
        for b in range(6):
            u = classify(a, b)
            tally[u.family] = tally.get(u.family, 0) + 1
            nf = f"{u.normal[0]}x{u.normal[1]:+d}"
            same = (u.a, u.b) == u.normal
            fate = "OPEN" if u.fate == Fate.OPEN else u.fate.upper()
            lines.append(f"  {u.label:<7} {u.family:<20} {fate:<32} "
                         f"{'' if same else '-> ' + nf}")
            if a >= 1 and b >= 1 and a % 2 == 1 and b % 2 == 1:
                tex.append((u.label, u.family, u.fate, nf, same))
    lines.append("")
    lines.append("family tally over the 36 cells:")
    for k, v in sorted(tally.items(), key=lambda kv: -kv[1]):
        lines.append(f"  {k:<22} {v}")

    # the nine cells carykh left unresolved
    lines.append("")
    lines.append("carykh's nine 'unique' universes (a, b both odd, both >= 1):")
    nine = [(a, b) for a in (1, 3, 5) for b in (1, 3, 5)]
    for a, b in nine:
        u = classify(a, b)
        nf = f"{u.normal[0]}x{u.normal[1]:+d}"
        verdict = {
            Fate.CYCLIC: "SOLVED: every orbit cycles",
            Fate.OPEN: "open",
        }.get(u.fate, u.fate)
        extra = "" if (u.a, u.b) == u.normal else f"  (equivalent to {nf})"
        lines.append(f"  {u.label:<6} {verdict}{extra}")
    distinct = sorted({classify(a, b).normal for a, b in nine
                       if classify(a, b).fate == Fate.OPEN})
    lines.append("")
    lines.append(f"  => genuinely open and pairwise inequivalent: "
                 + ", ".join(f"{a}x{b:+d}" for a, b in distinct))
    write("carykh_grid.txt", "\n".join(lines) + "\n")

    rows = []
    for a, b in nine:
        u = classify(a, b)
        nf = f"${u.normal[0]}x{u.normal[1]:+d}$"
        if u.fate == Fate.CYCLIC:
            st = r"\solved{every orbit cycles}"
        elif (u.a, u.b) != u.normal:
            st = r"\reduc{equivalent to %s}" % nf
        else:
            st = r"\openv{open}"
        rows.append(r"$%dx%+d$ & %s & %s \\" % (u.a, u.b, u.family.replace("_", " "), st))
    write("carykh_nine.tex",
          "%% generated by generate_data.py -- do not edit\n" + "\n".join(rows) + "\n")


