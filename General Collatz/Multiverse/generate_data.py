HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "data")
os.makedirs(DATA, exist_ok=True)


def write(name: str, text: str) -> None:
    r"""Write a data file.

    LaTeX subtlety: a file ending in a tabular row separator `\\` cannot be
    \input inside a tabular.  TeX peeks past the `\\` for an optional `[len]`
    argument, that lookahead crosses the end of the input file, and the
    `\bottomrule` waiting in the outer document is then read while the
    alignment is still mid-row -- "Misplaced \noalign".  So we strip a
    trailing `\\` here, and the paper supplies it before `\bottomrule`.
    """
    if name.endswith(".tex"):
        stripped = text.rstrip()
        if stripped.endswith(r"\\"):
            text = stripped[:-2].rstrip() + "\n"
    path = os.path.join(DATA, name)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"  wrote {os.path.relpath(path, HERE)}  ({len(text)} bytes)")


# ======================================================================
#  Inline figures
#
#  Every table in the paper is spliced in from data/ by inline_tables.py.
#  The figures quoted in *sentences* used to be typed straight into the .tex,
#  and they drifted: the residue-obstruction counts in the q-ary chapter were
#  left over from an older parameter setting and contradicted the very row of
#  the verification table that produced them.  So those numbers are now
#  emitted here as LaTeX macros (data/facts.tex), and the paper uses the
#  macros.  Nothing quoted in the paper is typed by hand any more.
# ======================================================================

FACTS: Dict[str, str] = {}


def _num(n: int) -> str:
    r"""12345 -> "12{,}345", the thousands separator the paper uses."""
    return "{,}".join(reversed([str(n)[max(0, i - 3):i]
                                for i in range(len(str(n)), 0, -3)]))


def write_facts() -> None:
    # A TeX control word is letters only, so a key with a digit in it produces
    # a macro LaTeX cannot parse -- and the failure is a wall of "Missing
    # number" errors a long way from the cause.  Catch it here instead.
    bad = sorted(k for k in FACTS if not k.isalpha())
    if bad:
        raise SystemExit("fact names must be letters only, got: "
                         + ", ".join(bad))
    body = "\n".join(r"\newcommand{\Fact%s}{%s}" % (k, v)
                     for k, v in sorted(FACTS.items()))
    write("facts.tex", "%% generated by generate_data.py -- do not edit\n"
          + body + "\n")
    write("facts.txt",
          "Inline figures quoted in the paper's prose\n" + "=" * 74 + "\n\n"
          + "\n".join(f"  {k:<24} {v}" for k, v in sorted(FACTS.items()))
          + "\n")


