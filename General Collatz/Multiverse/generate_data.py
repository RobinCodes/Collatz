def facts_cycle_through_one(a_max: int, b_max: int) -> None:
    """How often 1 is periodic, and how often that is the one-step case."""
    tot = pw = 0
    for a in range(1, a_max, 2):
        for b in range(1, b_max, 2):
            per, _ = mv.one_is_periodic(a, b)
            if not per:
                continue
            tot += 1
            if (a + b) & (a + b - 1) == 0:
                pw += 1
    FACTS["OneAMax"] = _num(a_max)
    FACTS["OneBMax"] = _num(b_max)
    FACTS["OneTotal"] = _num(tot)
    FACTS["OnePow"] = _num(pw)
    FACTS["OneOther"] = _num(tot - pw)


def facts_c4(a_lo: int, a_hi: int, b_hi: int, seed_hi: int) -> None:
    r"""Counterexamples to conjecture C4.

    C4: if 1 lies on a cycle C containing another odd number, then no odd
    number outside C enters C.  The scan is over odd a in [a_lo, a_hi] -- the
    row a = 1 is excluded because it is solved outright by the descent
    theorem, and reporting it alongside the open rows conflates the two.
    """
    viol = []
    for a in range(a_lo, a_hi + 1, 2):
        for b in range(1, b_hi + 1, 2):
            t, ci = mv.orbit(1, a, b, max_steps=5000, value_cap=10 ** 40)
            if ci is None:
                continue
            C = set(t[ci:])
            if 1 not in C or sum(1 for x in C if x % 2) < 2:
                continue
            for seed in range(1, seed_hi, 2):
                if seed in C:
                    continue
                u, cj = mv.orbit(seed, a, b, max_steps=20000,
                                 value_cap=10 ** 40)
                if cj is not None and any(x in C for x in u):
                    viol.append((a, b, seed))
                    break
    FACTS["CfourALo"] = _num(a_lo)
    FACTS["CfourAHi"] = _num(a_hi)
    FACTS["CfourBHi"] = _num(b_hi)
    FACTS["CfourSeedHi"] = _num(seed_hi)
    FACTS["CfourViol"] = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five",
                          6: "six", 7: "seven", 8: "eight",
                          9: "nine"}.get(len(viol), _num(len(viol)))


def facts_window(a: int, b: int, narrow: int, wide: int, steps: int) -> None:
    """The census entry that moves when the seed window widens."""
    FACTS["WindowB"] = _num(b)
    FACTS["WindowNarrow"] = _num(narrow)
    FACTS["WindowWide"] = _num(wide)
    FACTS["WindowNarrowCyc"] = _num(
        len(find_cycles(a, b, seed_max=narrow, max_steps=steps)))
    FACTS["WindowWideCyc"] = _num(
        len(find_cycles(a, b, seed_max=wide, max_steps=steps)))


# ======================================================================
#  Verification suite -- every theorem of the paper, checked numerically
# ======================================================================

def verify(quick: bool) -> None:
    R: List[Tuple[str, str, int, str]] = []   # (id, claim, cases, verdict)

    def rec(tag, claim, n, ok, detail=""):
        R.append((tag, claim, n, ("PASS" if ok else "FAIL " + detail)))
        print(f"    {tag:<8} {'PASS' if ok else 'FAIL'}  ({n} cases) {claim}")

    A = 40 if not quick else 16
    B = 40 if not quick else 16
    NN = 300 if not quick else 80
    STEPS = 400

    # -- Thm: halving symmetry.  Pointwise:  U = T_{2a,2b} satisfies
    #    U(n)  = T_{a,b}(n)                      for n even, and
    #    U(n)  = 2*T_{a,b}(n) (which is even),
    #    U^2(n)= T_{a,b}(n)                      for n odd.
    #    Hence the U-orbit of n is the T-orbit of n with one extra even term
    #    inserted after each odd step.
    n = 0
    ok = True
    for a in range(0, A):
        for b in range(0, B):
            U = lambda x: mv.step(x, 2 * a, 2 * b)
            for s in range(1, 200):
                n += 1
                if s % 2 == 0:
                    if U(s) != mv.step(s, a, b):
                        ok = False
                else:
                    if U(s) != 2 * mv.step(s, a, b) or U(s) % 2 != 0:
                        ok = False
                    if U(U(s)) != mv.step(s, a, b):
                        ok = False
    # and the orbit-level consequence: the U-trajectory is exactly the
    # T-trajectory with 2*T(x) spliced in after each odd x
    for a in range(0, A // 2):
        for b in range(0, B // 2):
            if a == 0 and b == 0:
                continue
            for s in range(1, 60):
                t1, _ = mv.orbit(s, a, b, max_steps=40, value_cap=10 ** 18)
                expect = []
                for x in t1:
                    expect.append(x)
                    if x % 2 == 1:
                        expect.append(2 * mv.step(x, a, b))
                t2, _ = mv.orbit(s, 2 * a, 2 * b, max_steps=len(expect),
                                 value_cap=10 ** 18)
                n += 1
                if t2 != expect[:len(t2)]:
                    ok = False
    rec("T-halve", "halving symmetry: T_{2a,2b} refines T_{a,b}", n, ok)

    # -- Thm: odd scaling.  d odd  =>  T_{a,db}(d n) = d T_{a,b}(n).
    n = 0
    ok = True
    for a in range(0, A):
        for b in range(0, B):
            for d in (1, 3, 5, 7, 9, 15):
                for s in range(1, 30):
                    n += 1
                    if mv.step(d * s, a, d * b) != d * mv.step(s, a, b):
                        ok = False
    rec("T-scale", "odd scaling: T_{a,db}(dn) = d T_{a,b}(n) for odd d", n, ok)

    # -- Thm: p-adic stratification (i), attraction.
    n = 0
    ok = True
    for a in range(1, A):
        for b in range(1, B):
            att = mv.attracting_primes(a, b)
            for p, e in att.items():
                D = p ** e
                for s in range(1, 60):
                    t, _ = mv.orbit(s, a, b, max_steps=200, value_cap=10 ** 24)
                    # after the e-th odd step the orbit must be inside D*Z forever
                    odd_seen = 0
                    entered = None
                    for i, x in enumerate(t):
                        if x % 2 == 1:
                            odd_seen += 1
                            if odd_seen >= e and entered is None:
                                entered = i + 1
                    if entered is not None and entered < len(t):
                        n += 1
                        if any(x % D for x in t[entered:]):
                            ok = False
    rec("T-attr", "attraction: p | gcd(a,b) forces every orbit into p^{v_p(b)}Z",
        n, ok)

    # -- Thm: p-adic stratification (ii), repulsion.
    n = 0
    ok = True
    for a in range(1, A):
        for b in range(1, B):
            rep = mv.repelling_primes(a, b)
            for p, e in rep.items():
                for s in range(1, 60):
                    t, _ = mv.orbit(s, a, b, max_steps=120, value_cap=10 ** 24)
                    inv = [min(mv.vp(x, p) if x % p == 0 else 0, e) for x in t if x]
                    n += 1
                    if len(set(inv)) > 1:
                        ok = False
    rec("T-rep", "repulsion: min(v_p(n), v_p(b)) is an orbit invariant when "
        "p | b, p does not divide a", n, ok)

    # -- Thm: normal form is coprime and idempotent.
    n = 0
    ok = True
    for a in range(1, 200):
        for b in range(1, 200):
            nf = normal_form(a, b)
            n += 1
            if math.gcd(nf[0], nf[1]) != 1:
                ok = False
            if normal_form(*nf) != nf:
                ok = False
    # the boundary the theorem excludes: at a = 0 every prime divides a, the
    # reduction is not defined, and coprimality genuinely fails -- so check
    # instead that nothing ever asks for it, i.e. that a = 0 is classified
    # outright as the constant family.
    for b in range(1, 200):
        n += 1
        if classify(0, b).family != Family.CONSTANT:
            ok = False
    rec("T-norm", "normal form is coprime and idempotent for a >= 1; a = 0 is "
        "classified without reduction", n, ok)

    # -- Thm: parity runaway.
    n = 0
    ok = True
    for a in range(1, A):
        for b in range(1, B):
            if (a + b) % 2 == 0:
                continue
            for s in range(1, 40):
                t, cyc = mv.orbit(s, a, b, max_steps=STEPS, value_cap=10 ** 400)
                n += 1
                if cyc is not None:
                    ok = False
    rec("T-parity", "a + b odd (a,b >= 1): no orbit is ever periodic", n, ok)

    # -- Thm: a = 1, b odd -- descent bound.
    n = 0
    ok = True
    for b in range(1, 120, 2):
        for s in range(1, 400):
            t, cyc = mv.orbit(s, 1, b, max_steps=4000)
            n += 1
            if cyc is None or min(t[cyc:]) > b:
                ok = False
    rec("T-desc", "a = 1, b odd: every orbit cycles, with least cycle element "
        "<= b", n, ok)

    # -- Thm: a = 0 -- unique cycle of length v2(b)+1.
    n = 0
    ok = True
    for b in range(1, 200):
        cs = find_cycles(0, b, seed_max=200, max_steps=200)
        n += 1
        if len(cs) != 1 or cs[0].length != mv.v2(b) + 1:
            ok = False
    rec("T-const", "a = 0: exactly one cycle, of length v_2(b) + 1", n, ok)

    # -- Thm: b = 0 -- shapes.
    n = 0
    ok = True
    for a in range(1, 40):
        u = classify(a, 0)
        pow2 = (a & (a - 1)) == 0
        n += 1
        if pow2 != (u.fate == Fate.CYCLIC):
            ok = False
        if pow2:
            for s in (1, 3, 5, 7, 9):
                t, c = mv.orbit(s, a, 0, max_steps=200)
                if c is None or len(t) - c != mv.v2(a) + 1 if a > 1 else False:
                    ok = False
    rec("T-shape", "b = 0: every orbit cycles iff a is a power of two, with "
        "period log2(a) + 1", n, ok)

    # -- Thm: cycle equation.
    n = 0
    ok = True
    pairs = [(a, b) for a in (1, 3, 5, 7, 9) for b in range(1, 40, 2)]
    for a, b in pairs:
        for c in find_cycles(a, b, seed_max=NN, max_steps=8000):
            n += 1
            if cycle_equation_residual(c) != 0:
                ok = False
    rec("T-cyceq", "cycle equation n1(2^m - a^k) = b * sum a^{k-i} 2^{...}", n, ok)

    # -- Thm: divisor decomposition of the cycle set.
    n = 0
    ok = True
    checks = [(3, b) for b in (5, 7, 15, 25, 35, 45, 49, 55, 63, 75, 77)]
    checks += [(5, b) for b in (3, 7, 9, 15, 21)]
    checks += [(7, b) for b in (3, 5, 9, 15)]
    for a, b in checks:
        cs = find_cycles(a, b, seed_max=NN * 4, max_steps=40000)
        for d, cl in decompose_cycles(a, b, cs).items():
            if d == 1:
                continue
            sub = find_cycles(a, b // d, seed_max=NN * 4, max_steps=40000)
            want = sorted(c.elements for c in sub if c.is_primitive)
            got = sorted(tuple(x // d for x in c.elements) for c in cl)
            n += 1
            if not set(map(tuple, want)) >= set(map(tuple, got)):
                ok = False
                print(f"      mismatch at {a}x+{b}, d={d}")
    rec("T-decomp", "divisor decomposition: the d-graded part of Cyc(T_{a,b}) "
        "is d * PrimCyc(T_{a,b/d})", n, ok)

    # -- Thm: attracting reduction preserves the cycle set exactly.
    n = 0
    ok = True
    for a in (3, 5, 7, 9):
        for b in range(1, 60, 2):
            u = classify(a, b)
            if not u.attracting:
                continue
            D = 1
            for p, e in u.attracting.items():
                D *= p ** e
            c1 = find_cycles(a, b, seed_max=800, max_steps=20000)
            c2 = find_cycles(a, b // D, seed_max=800, max_steps=20000)
            n += 1
            if sorted(tuple(x // D for x in c.elements) for c in c1) != \
               sorted(c.elements for c in c2):
                ok = False
                print(f"      mismatch at {a}x+{b} (D={D})")
    rec("T-attred", "attracting reduction is a bijection on cycles, scaling by D",
        n, ok)

    # -- Knowledge ladder: internal consistency of the four tiers.
    n = 0
    ok = True
    for a in range(0, 120):
        for b in range(0, 120):
            u = classify(a, b)
            k = mv.knowledge(a, b)
            nf = u.normal
            nu = classify(*nf)
            minimal = (u.a, abs(u.b)) == nf
            n += 1
            if k == mv.Knowledge.OPEN:
                ok &= (nu.fate == Fate.OPEN and minimal
                       and u.family == Family.PRIMITIVE)
            elif k == mv.Knowledge.REDUCIBLE:
                ok &= (nu.fate == Fate.OPEN and not minimal)
            elif k == mv.Knowledge.DECIDED:
                ok &= (nu.fate in Fate.PROVED and nu.family == Family.DESCENT)
            elif k == mv.Knowledge.CLOSED:
                ok &= (nu.fate in Fate.PROVED and nu.family != Family.DESCENT)
            else:
                ok = False
    rec("T-tier", "knowledge ladder: OPEN = minimal + open normal form, "
        "DECIDED = the a=1 row, CLOSED = proved with closed-form cycles", n, ok)

    # -- Z: invariance of the two half-lines, and finiteness of crossing.
    n = 0
    ok = True
    for a in range(0, 30):
        for b in range(-30, 31):
            escP = any(mv.step(x, a, b) <= 0 for x in range(1, 300))
            escN = any(mv.step(x, a, b) >= 0 for x in range(-300, 0))
            n += 2
            ok &= (escP != (a + b >= 1))
            ok &= (escN != (b <= a - 1))
    rec("T-Zhalf", "Z>0 invariant iff a+b >= 1; Z<0 invariant iff b <= a-1",
        n, ok)

    n = 0
    ok = True
    for a in range(1, 30):
        for b in range(-30, 31):
            for x in range(-400, 401):
                if x == 0:
                    continue
                y = mv.step(x, a, b)
                crossed = (x > 0 and y <= 0) or (x < 0 and y >= 0)
                n += 1
                if crossed and (x % 2 == 0 or abs(x) * a > abs(b)):
                    ok = False
    rec("T-Zcross", "sign changes only at odd n with |n| <= |b|/a", n, ok)

    # -- Thm: 1 is periodic iff its orbit meets a power of two.
    n = 0
    ok = True
    for a in range(1, 60):
        for b in range(1, 60):
            t, ci = mv.orbit(1, a, b, max_steps=4000, value_cap=10 ** 60)
            on = ci is not None and 1 in t[ci:]
            hits = any(x > 0 and (x & (x - 1)) == 0 for x in t[1:])
            n += 1
            ok &= (on == hits)
    rec("T-one", "1 lies on a cycle iff the orbit of 1 meets a power of two",
        n, ok)

    n = 0
    ok = True
    for b in range(1, 80):
        for k in range(1, 14):
            a = 2 ** k - b
            if a < 1:
                continue
            t, ci = mv.orbit(1, a, b, max_steps=200)
            n += 1
            ok &= (ci is not None and 1 in t[ci:] and len(t) - ci == k + 1)
    rec("T-onestep", "a + b = 2^k gives a cycle through 1 of period k+1", n, ok)

    # -- Thm: every cycle of x+b lies in [1, 2b].
    n = 0
    ok = True
    sharp = 0
    DESC_B = 159 if not quick else 39
    for b in range(1, DESC_B + 1, 2):
        for c in find_cycles(1, b, seed_max=4 * b + 40, max_steps=20000):
            n += 1
            ok &= (c.minimum >= 1 and c.maximum <= 2 * b and c.minimum <= b)
            sharp += (c.maximum == 2 * b)
    rec("T-desc2b", "every cycle of x+b is contained in [1, 2b]", n, ok)
    FACTS["DescB"] = _num(DESC_B)
    FACTS["DescCycles"] = _num(n)
    FACTS["DescSharp"] = _num(sharp)

    # -- Thm: the cycle-seed scaling needs m ODD.
    n = 0
    ok = True
    scale_hits = 0
    for a in (3, 5, 7):
        for b in (1, 3, 5):
            for c in find_cycles(a, b, seed_max=800, max_steps=20000):
                for m in (3, 5, 7, 9):
                    n += 1
                    img = tuple(m * x for x in c.elements)
                    hit = all(mv.step(img[i], a, m * b) == img[(i + 1) % len(img)]
                              for i in range(len(img)))
                    scale_hits += hit
                    ok &= hit
    rec("T-seedscale", "n on a cycle of ax+b => mn on a cycle of ax+mb for ODD m",
        n, ok)
    FACTS["ScaleCases"] = _num(n)
    FACTS["ScaleHits"] = _num(scale_hits)

    # the same census with EVEN m, which is where the earlier note went wrong
    ne = fe = 0
    for a in (3, 5, 7):
        for b in (1, 3, 5, 7):
            for c in find_cycles(a, b, seed_max=800, max_steps=20000):
                for m in (2, 4, 6, 8):
                    ne += 1
                    img = tuple(m * x for x in c.elements)
                    if not all(mv.step(img[i], a, m * b) == img[(i + 1) % len(img)]
                               for i in range(len(img))):
                        fe += 1
    FACTS["EvenMCases"] = _num(ne)
    FACTS["EvenMFail"] = _num(fe)

    # -- Refutation: g(x)=cx does NOT conjugate T_(a,b) to T_(ca,cb).
    n = 0
    lifts = 0
    for a in (3, 5, 7):
        for b in (1, 3, 5):
            for c in find_cycles(a, b, seed_max=800, max_steps=20000):
                for k in (3, 5, 7, 9):
                    n += 1
                    img = tuple(k * x for x in c.elements)
                    if all(mv.step(img[i], k * a, k * b) == img[(i + 1) % len(img)]
                           for i in range(len(img))):
                        lifts += 1
    rec("T-noconj", "cC is NEVER a cycle of T_(ca,cb) (the refuted conjugacy)",
        n, lifts == 0)
    FACTS["NoconjCases"] = _num(n)
    FACTS["NoconjHits"] = _num(lifts)

    # -- Thm: normal form is (a,1) iff rad(b) | a.
    n = 0
    ok = True
    for a in range(1, 120):
        for b in range(1, 120, 2):
            rad_divides = all(a % p == 0 for p in mv.factorise(b))
            n += 1
            ok &= ((normal_form(a, b) == (a, 1)) == rad_divides)
    rec("T-radical", "nf(a,b) = (a,1) iff rad(b) | a  (b odd)", n, ok)

    # -- q-ary: the two symmetries and the residue obstruction.
    import itertools
    import qary as QA

    def qcoeffs(q, lo, hi, cap):
        return list(itertools.product(range(lo, hi), repeat=q - 1))[:cap]

    n = 0
    ok = True
    for q in (2, 3, 4, 5):
        for aa in qcoeffs(q, 0, 4, 30 if not quick else 8):
            for bb in qcoeffs(q, 0, 4, 30 if not quick else 8):
                m = QA.QMap(q, aa, bb)
                m2 = m.scaled(q)
                for x in range(1, 40):
                    n += 1
                    if x % q == 0:
                        ok &= (m2.step(x) == m.step(x))
                    else:
                        ok &= (m2.step(x) == q * m.step(x))
                        ok &= (m2.step(m2.step(x)) == m.step(x))
    rec("T-qscale", "q-ary scaling: F_(qa,qb) refines F_(a,b)", n, ok)

    n = 0
    ok = True
    for q in (2, 3, 5, 7):
        for aa in qcoeffs(q, 1, 4, 25 if not quick else 6):
            for bb in qcoeffs(q, 0, 4, 25 if not quick else 6):
                m = QA.QMap(q, aa, bb)
                for d in range(1, 2 * q):
                    if math.gcd(d, q) != 1:
                        continue
                    md = m.offset_scaled(d)
                    for x in range(1, 40):
                        n += 1
                        ok &= (md.step(d * x) == d * m.step(x))
    rec("T-qtwist", "q-ary twisted scaling: n -> dn permutes the branches",
        n, ok)

    n = 0
    ngrow = 0
    ok = True
    QMAX = 5 if not quick else 3
    for q in range(2, QMAX + 1):
        for aa in qcoeffs(q, 0, 4, 25 if not quick else 6):
            for bb in qcoeffs(q, 0, 4, 25 if not quick else 6):
                m = QA.QMap(q, aa, bb)
                g = QA.residue_graph(m)
                for r in QA.escaping_residues(m):
                    vis = set()
                    j = r
                    while j not in vis:
                        vis.add(j)
                        j = g[j]
                    grows = all(m.a[k - 1] >= 2 or
                                (m.a[k - 1] == 1 and m.b[k - 1] >= 1)
                                for k in vis)
                    for x in range(r, 200, q):
                        if x < 1:
                            continue
                        t, ci = m.orbit(x, max_steps=60, value_cap=10 ** 60)
                        n += 1
                        # (i) never divides
                        ok &= not any(y % q == 0 for y in t[1:])
                        # (ii) and grows, when the growth condition holds
                        if grows:
                            ngrow += 1
                            ok &= (ci is None and (len(t) < 3 or t[-1] > t[0]))
    rec("T-resobs", "residue obstruction: escaping residues never divide, and "
        "diverge under the growth condition", n, ok)
    FACTS["ResobsQ"] = str(QMAX)
    FACTS["ResobsOrbits"] = _num(n)
    FACTS["ResobsGrowth"] = _num(ngrow)

    # -- q-ary attracting sublattice: the induced coefficients are PERMUTED.
    n = 0
    ok = True
    for q in (2, 3, 4, 5, 7):
        for mm in range(2, 8):
            if math.gcd(mm, q) != 1:
                continue
            for aa in qcoeffs(q, 1, 4, 12 if not quick else 4):
                for bb in qcoeffs(q, 0, 4, 12 if not quick else 4):
                    A = [mm * x for x in aa]
                    B = [mm * x for x in bb]
                    G = QA.QMap(q, A, B)
                    H = QA.QMap(q,
                                [A[(mm * j) % q - 1] for j in range(1, q)],
                                [B[(mm * j) % q - 1] // mm for j in range(1, q)])
                    for k in range(1, 40):
                        n += 1
                        ok &= (G.step(mm * k) % mm == 0)
                        ok &= (G.step(mm * k) // mm == H.step(k))
    rec("T-qattract", "attracting sublattice: the induced map has coefficients "
        "a'_j = a_(mj mod q), b'_j = b_(mj mod q)/m", n, ok)

    # -- the primality map of the "beyond modularity" section.  Memoised, so
    #    the range the paper quotes in prose is also the range checked here.
    LIM = 4000 if quick else 200000
    seen_cycles, _basins, failed, _peak = primality_census(LIM)
    ok = (failed == 0 and len(seen_cycles) == 2)
    rec("T-primmap", "primality map: every seed tested is eventually periodic, "
        "with exactly two cycles", LIM, ok)

    # -- carykh's (k, m) pairs for 3x+5, and the cycle-equation bound.
    km = {(c.k, c.m) for c in find_cycles(3, 5, seed_max=800 if not quick else 200,
                                          max_steps=20000)}
    n = len(km)
    ok = {(3, 5), (17, 27)} <= km and all(2 ** m > 3 ** k for k, m in km)
    rec("T-km", "3x+5 has cycles with (k,m) = (3,5) and (17,27), and every "
        "cycle has 2^m > a^k", n, ok)
    FACTS["KmOne"] = "3, 5"
    FACTS["KmTwo"] = "17, 27"

    # -- Prop: the b = 0 relative peak is exactly 2^(t-1+2^-t).
    n = 0
    ok = True
    PEAK_N = 200000 if not quick else 5000
    meas = []
    for t in (1, 2, 3):
        st = growth_statistics(2 ** t, 0, n_max=PEAK_N, max_steps=2000,
                               value_cap=10 ** 24)
        exact = 2.0 ** (t - 1 + 2.0 ** -t)
        n += 1
        ok &= (abs(st["peak"] - exact) < 5e-7)
        meas.append((exact, st["peak"]))
    rec("T-peak", "b = 0, a = 2^t: geometric mean relative peak is "
        "2^(t-1+2^-t)", n, ok)
    FACTS["PeakN"] = _num(PEAK_N)
    FACTS["PeakOne"] = "%.6f" % meas[0][0]
    FACTS["PeakTwo"] = "%.6f" % meas[1][0]
    FACTS["PeakThree"] = "%.6f" % meas[2][0]
    # "six decimal places" is not an observation typed in after the fact: the
    # tolerance above IS that claim, so the check fails if agreement is worse.
    FACTS["PeakDigits"] = "six"

    # -- Thm: negation duality.
    n = 0
    ok = True
    for a in range(1, 12):
        for b in range(1, 30):
            for s in range(1, 30):
                t1, _ = mv.orbit(s, a, -b, max_steps=60, value_cap=10 ** 18)
                t2, _ = mv.orbit(-s, a, b, max_steps=60, value_cap=10 ** 18)
                n += 1
                if [-x for x in t1] != t2:
                    ok = False
    rec("T-neg", "negation duality: -T_{a,b}(n) = T_{a,-b}(-n)", n, ok)

    total = len(R)
    passed = sum(1 for _, _, _, v in R if v == "PASS")
    lines = ["Numerical verification of the paper's theorems",
             "(these are checks, not proofs; the proofs are in the paper)",
             "=" * 78, ""]
    for tag, claim, cases, verdict in R:
        lines.append(f"{tag:<10} {verdict:<8} {cases:>9} cases   {claim}")
    lines.append("")
    lines.append(f"{passed}/{total} checks pass")
    write("verification.txt", "\n".join(lines) + "\n")

