def table_decomposition(a: int, bs: Sequence[int], seed_max: int,
                        max_steps: int) -> None:
    lines = ["Divisor decomposition of the cycle set",
             "",
             "  Cyc(T_{a,b})  =  disjoint union over odd d | b  of  "
             "d * PrimCyc(T_{a, b/d})",
             "",
             "verified by grouping each cycle by its repelling-prime content "
             "and dividing through",
             "=" * 78]
    tex = []
    for b in bs:
        cs = find_cycles(a, b, seed_max=seed_max, max_steps=max_steps)
        groups = decompose_cycles(a, b, cs)
        lines.append("")
        lines.append(f"f(x) = {a}x + {b}   ({len(cs)} cycles found)")
        pieces = []
        for d, cl in groups.items():
            sub = f"{a}x{b // d:+d}"
            lines.append(f"   d = {d:<5}  {len(cl):>2} cycle(s)  =  {d} * "
                         f"primitive cycles of {sub}")
            for c in cl:
                lines.append(f"        len {c.length:<3} k={c.k:<3} m={c.m:<3} "
                             f"min={c.minimum:<7} max={c.maximum:<12} "
                             f"eqn residual {cycle_equation_residual(c)}")
            pieces.append(r"%d{\cdot}\mathrm{P}(%dx%+d)^{%d}" % (d, a, b // d, len(cl)))
        tex.append(r"$%dx%+d$ & $%d$ & $%s$ \\" % (a, b, len(cs), " \\;\\sqcup\\; ".join(pieces)))
    write("decomposition.txt", "\n".join(lines) + "\n")
    write("decomposition.tex",
          "%% generated by generate_data.py -- do not edit\n" + "\n".join(tex) + "\n")


# ======================================================================
#  Table 5 -- density of open universes
# ======================================================================

def table_density(limits: Sequence[int]) -> None:
    """Two densities.

      * ALL open universes -- those whose normal form is primitive with
        a' >= 3.  Since the normal form has a' = a / 2^s with
        s = min(v2(a), v2(b)), a universe is open iff v2(a) = v2(b) and
        a / 2^s >= 3.  Powers of two have density 0, so the predicted
        density is  P(v2(a) = v2(b)) = sum_s 4^{-s-1} = 1/3.

      * IRREDUCIBLE open universes -- those already in normal form:
        a >= 3 odd, b odd, gcd(a, b) = 1.  Predicted density
        (1/4) * prod_{p odd}(1 - p^-2) = (1/4)(8/pi^2) = 2/pi^2.
    """
    third = 1 / 3
    twopi = 2 / math.pi ** 2
    lines = ["Density of open universes",
             "",
             "  open              : normal form is primitive (a' >= 3 odd, b' odd)",
             "  open irreducible  : additionally already in normal form,",
             "                      i.e. a >= 3 odd, b odd, gcd(a,b) = 1",
             "",
             f"  predicted open density         = 1/3     = {third:.6f}",
             f"  predicted irreducible density  = 2/pi^2  = {twopi:.6f}",
             "=" * 78, "",
             f"{'N':>7} {'open':>10} {'open irr':>10} {'proved':>10} "
             f"{'open/N^2':>10} {'1/3':>8} {'irr/N^2':>10} {'2/pi^2':>10}"]
    rows = []
    for N in limits:
        op = opi = pr = 0
        for a in range(1, N + 1):
            for b in range(1, N + 1):
                u = classify(a, b)
                if u.fate == Fate.OPEN:
                    op += 1
                    if not u.is_reducible:
                        opi += 1
                else:
                    pr += 1
        f1, f2 = op / (N * N), opi / (N * N)
        lines.append(f"{N:>7} {op:>10} {opi:>10} {pr:>10} {f1:>10.6f} "
                     f"{third:>8.4f} {f2:>10.6f} {twopi:>10.6f}")
        rows.append(r"$%d$ & $%d$ & $%.6f$ & $%d$ & $%.6f$ \\"
                    % (N, op, f1, opi, f2))
    write("density.txt", "\n".join(lines) + "\n")
    write("density.tex",
          "%% generated by generate_data.py -- do not edit\n" + "\n".join(rows) + "\n")


# ======================================================================
#  Table 5b -- the knowledge ladder
# ======================================================================

def table_tiers(limits: Sequence[int]) -> None:
    """Census of the four Knowledge tiers, against their limiting densities.

        CLOSED     -> 2/3          (everything proved except the a=1 row)
        DECIDED    -> 0            (a' = 1 forces a to be a power of two)
        REDUCIBLE  -> 1/3 - 2/pi^2
        OPEN       -> 2/pi^2
    """
    pred = {
        mv.Knowledge.CLOSED:    2 / 3,
        mv.Knowledge.DECIDED:   0.0,
        mv.Knowledge.REDUCIBLE: 1 / 3 - 2 / math.pi ** 2,
        mv.Knowledge.OPEN:      2 / math.pi ** 2,
    }
    SHORT = {mv.Knowledge.CLOSED: "CLOSED", mv.Knowledge.DECIDED: "DECIDED",
             mv.Knowledge.REDUCIBLE: "REDUCIBLE", mv.Knowledge.OPEN: "OPEN"}
    lines = ["The knowledge ladder", "",
             "  CLOSED     fate proved AND the cycle set in closed form",
             "  DECIDED    fate proved, cycles computable, no formula in b",
             "  REDUCIBLE  fate unknown, but equivalent to a smaller open universe",
             "  OPEN       fate unknown and irreducible -- its own normal form",
             "",
             "limiting densities: " + ", ".join(
                 f"{SHORT[k]} {v:.6f}" for k, v in pred.items()),
             "=" * 78, "",
             f"{'N':>7} " + " ".join(f"{SHORT[k]:>12}" for k in mv.Knowledge.ORDER)]
    rows = []
    for N in limits:
        c = {k: 0 for k in mv.Knowledge.ORDER}
        for a in range(1, N + 1):
            for b in range(1, N + 1):
                c[mv.knowledge(a, b)] += 1
        tot = N * N
        lines.append(f"{N:>7} " + " ".join(f"{c[k] / tot:>12.6f}"
                                           for k in mv.Knowledge.ORDER))
        rows.append(r"$%d$ & %s \\" % (
            N, " & ".join(f"${c[k] / tot:.6f}$" for k in mv.Knowledge.ORDER)))
    lines.append("")
    lines.append(f"{'limit':>7} " + " ".join(
        f"{pred[k]:>12.6f}" for k in mv.Knowledge.ORDER))
    rows.append(r"limit & %s \\" % " & ".join(
        f"${pred[k]:.6f}$" for k in mv.Knowledge.ORDER))
    write("tiers.txt", "\n".join(lines) + "\n")
    write("tiers.tex",
          "%% generated by generate_data.py -- do not edit\n" + "\n".join(rows) + "\n")


# ======================================================================
#  Table 6 -- growth statistics heat map (carykh's average max growth)
# ======================================================================

def table_growth(a_max: int, b_max: int, n_max: int) -> None:
    """The relative-peak heat map, WITH the fraction of seeds it rests on.

    `growth_statistics` drops any seed that leaves the step or value budget
    before it repeats, and averages what is left.  For a contracting row that
    is every seed; for an expanding one it can be a few per cent, and the
    printed mean is then a conditional average over an exceptional set of
    non-diverging seeds rather than a typical value.  Reporting the peak
    without that percentage -- which an earlier version did -- makes the
    a >= 5 rows look comparable with the a <= 3 rows when they are not, so the
    counted percentage travels with every cell.
    """
    lines = [f"Average relative peak (geometric mean of max(orbit(n))/n) and "
             f"average path length,",
             f"over seeds n = 1..{n_max}.",
             "'RUN' = every seed exceeded the value or step budget (runaway).",
             "'counted' = percentage of the seeds that stayed inside the",
             "budget; the means are over those seeds only.",
             "=" * 78, ""]
    grid_peak: Dict[Tuple[int, int], object] = {}
    for a in range(0, a_max + 1):
        for b in range(0, b_max + 1):
            st = growth_statistics(a, b, n_max=n_max, max_steps=2000,
                                   value_cap=10 ** 24)
            grid_peak[(a, b)] = st
    hdr = "  a\\b " + "".join(f"{b:>9}" for b in range(b_max + 1))
    lines.append("AVERAGE RELATIVE PEAK")
    lines.append(hdr)
    for a in range(a_max + 1):
        cells = []
        for b in range(b_max + 1):
            st = grid_peak[(a, b)]
            cells.append("      RUN" if st["peak"] is None else f"{st['peak']:>9.3f}")
        lines.append(f"{a:>5} " + "".join(cells))
    lines.append("")
    lines.append("AVERAGE PATH LENGTH")
    lines.append(hdr)
    for a in range(a_max + 1):
        cells = []
        for b in range(b_max + 1):
            st = grid_peak[(a, b)]
            cells.append("      RUN" if st["path"] is None else f"{st['path']:>9.2f}")
        lines.append(f"{a:>5} " + "".join(cells))
    lines.append("")
    lines.append("PERCENTAGE OF SEEDS COUNTED")
    lines.append(hdr)
    for a in range(a_max + 1):
        cells = []
        for b in range(b_max + 1):
            st = grid_peak[(a, b)]
            pc = 100.0 * (1.0 - st["runaway_fraction"])
            cells.append("      RUN" if st["peak"] is None else f"{pc:>8.1f}%")
        lines.append(f"{a:>5} " + "".join(cells))
    write("growth.txt", "\n".join(lines) + "\n")

    rows = []
    worst = 100.0
    for a in range(a_max + 1):
        cells = []
        for b in range(b_max + 1):
            st = grid_peak[(a, b)]
            if st["peak"] is None:
                cells.append(r"\rn")
                continue
            pc = 100.0 * (1.0 - st["runaway_fraction"])
            if pc >= 99.95:
                cells.append(f"{st['peak']:.2f}")
            else:
                worst = min(worst, pc)
                cells.append(r"%.2f\,\pct{%d}" % (st["peak"], round(pc)))
        rows.append(f"${a}$ & " + " & ".join(cells) + r" \\")
    write("growth.tex",
          "%% generated by generate_data.py -- do not edit\n" + "\n".join(rows) + "\n")
    FACTS["GrowthSeeds"] = _num(n_max)
    FACTS["GrowthWorstCounted"] = "%d" % round(worst)
    # the three cells the text quotes to three decimals (LaTeX macro names
    # cannot contain digits, hence the spelled-out suffixes)
    for b, word in ((0, "Zero"), (2, "Two"), (6, "Six")):
        if b <= b_max and grid_peak[(2, b)]["peak"] is not None:
            FACTS["GrowthRowTwo" + word] = "%.3f" % grid_peak[(2, b)]["peak"]


