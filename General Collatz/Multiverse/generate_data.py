def table_grid(a_max: int = 12, b_max: int = 12) -> None:
    write("grid.txt", mv.render_grid(a_max, b_max) + "\n")

    # LaTeX version, coloured by family
    colour = {
        Family.CONSTANT: "gCon", Family.PURE_SHAPE: "gShp",
        Family.PURE_RUNAWAY: "gRun", Family.PARITY_RUNAWAY: "gRun",
        Family.HALVING: "gHal", Family.ATTRACTING: "gAtt",
        Family.DESCENT: "gDes", Family.PRIMITIVE: "gOpen",
    }
    rows = []
    header = " & ".join([r"$a\backslash b$"] + [str(b) for b in range(b_max + 1)])
    rows.append(header + r" \\ \midrule")
    for a in range(a_max + 1):
        cells = []
        for b in range(b_max + 1):
            u = classify(a, b)
            cells.append(r"\cell{%s}{%s}" % (colour[u.family], mv.CODE[u.family]))
        rows.append(f"${a}$ & " + " & ".join(cells) + r" \\")
    body = "\n".join(rows)
    spec = "r" + "c" * (b_max + 1)
    write("grid.tex",
          "%% generated by generate_data.py -- do not edit\n"
          "\\begin{tabular}{@{}%s@{}}\n\\toprule\n%s\n\\bottomrule\n\\end{tabular}\n"
          % (spec, body))


