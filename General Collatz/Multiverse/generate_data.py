"""
generate_data.py -- regenerate every table and figure used in the paper
    ../paper/collatz_multiverse.tex

Run:  python3 generate_data.py [--quick]

Outputs land in ./data/ as both human-readable .txt and \\input-able .tex.
Two kinds of output:

  * TABLES -- data/<name>.tex, a run of tabular rows, spliced by
    inline_tables.py between the "% >>>BEGIN-DATA <name>" markers.
  * INLINE FIGURES -- data/facts.tex, a run of \\newcommand definitions for
    every number the paper quotes in a *sentence*.  These used to be typed
    into the .tex and they drifted (the q-ary residue-obstruction counts
    ended up contradicting the verification table that produced them), so
    the prose now uses \\Fact... macros and nothing measured is typed by hand.

The verification suite runs last and its results are a table too, so a check
that starts failing is visible in the paper rather than only on the console.
"""

