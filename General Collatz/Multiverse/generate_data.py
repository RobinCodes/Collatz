#  The primality map (the "beyond modularity" chapter)
# ======================================================================

def primality_census(limit: int):
    """Cycles and basin sizes of the primality map over seeds 1..limit.

    Memoised across seeds, so the whole range costs one pass.  Returns
    (cycles, basins, failed, peak) with `cycles` a list of sorted tuples
    ordered by decreasing basin and `peak` the largest value reached from any
    seed in the range -- which is how far the density experiment below can and
    cannot see.
    """
    pm = QA.primality_map()
    settled: Dict[int, int] = {}
    index: Dict[Tuple[int, ...], int] = {}
    basin: Dict[int, int] = {}
    failed = 0
    peak = [0]                      # largest value any orbit from 1..limit hits
    for seed in range(1, limit + 1):
        n, seen, traj = seed, {}, []
        while True:
            if n in settled:
                cid = settled[n]
                break
            if n in seen:
                key = tuple(sorted(traj[seen[n]:]))
                cid = index.setdefault(key, len(index))
                break
            if len(traj) > 100000:
                cid = -1
                failed += 1
                break
            seen[n] = len(traj)
            traj.append(n)
            n = pm.step(n)
        basin[cid] = basin.get(cid, 0) + 1
        for x in traj:
            settled[x] = cid
        if traj:
            peak[0] = max(peak[0], max(traj))
    order = sorted(index.items(), key=lambda kv: -basin.get(kv[1], 0))
    return ([k for k, _ in order],
            [basin.get(i, 0) for _, i in order],
            failed, peak[0])


