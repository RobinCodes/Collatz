#  Table 3 -- cycle census for the 3x+b row  (Artem's chart)
# ======================================================================

def table_row_cycles(a: int, b_max: int, seed_max: int, max_steps: int,
                     stem: str) -> List[Tuple[int, int, int, Tuple[int, int]]]:
    """Cycle counts for T_{a,b}, b odd, 1 <= b <= b_max."""
    out = []
    t0 = time.time()
    for b in range(1, b_max + 1, 2):
        cs = find_cycles(a, b, seed_max=seed_max, max_steps=max_steps)
        prim = [c for c in cs if c.is_primitive]
        out.append((b, len(cs), len(prim), normal_form(a, b)))
    print(f"    ({time.time() - t0:.1f}s)")

    lines = [f"Cycle census for f(x) = {a}x + b,  b odd <= {b_max}",
             f"search: seeds 1..{seed_max}, step budget {max_steps}",
             "counts are LOWER BOUNDS -- a cycle whose basin misses the seed "
             "window is not found",
             "=" * 78, "",
             f"{'b':>5} {'cycles':>7} {'primitive':>10} {'normal form':>14}  notes"]
    for b, n, p, nf in out:
        u = classify(a, b)
        note = []
        if u.attracting:
            note.append("attracting " + ",".join(f"{q}^{e}" for q, e in sorted(u.attracting.items())))
        if u.repelling:
            note.append("repelling " + ",".join(f"{q}^{e}" for q, e in sorted(u.repelling.items())))
        lines.append(f"{b:>5} {n:>7} {p:>10} {nf[0]}x{nf[1]:+d}".ljust(40)
                     + "; ".join(note))
    write(f"{stem}.txt", "\n".join(lines) + "\n")

    # LaTeX: 4 columns of (b, total, primitive)
    per = (len(out) + 3) // 4
    cols = [out[i * per:(i + 1) * per] for i in range(4)]
    body = []
    for r in range(per):
        cells = []
        for c in cols:
            if r < len(c):
                b, n, p, _ = c[r]
                cells += [str(b), str(n), str(p)]
            else:
                cells += ["", "", ""]
        body.append(" & ".join(cells) + r" \\")
    write(f"{stem}.tex",
          "%% generated by generate_data.py -- do not edit\n" + "\n".join(body) + "\n")
    return out


